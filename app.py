@app.route("/results")
@login_required
def results():
    role = session.get("role")
    user_id = session["user_id"]

    if role == "student":
        students = query("""
            SELECT id, student_number, full_name
            FROM public.school_students
            WHERE user_id=%s
        """, (user_id,))

    elif role == "parent":
        students = query("""
            SELECT s.id, s.student_number, s.full_name
            FROM public.school_students s
            JOIN public.parent_students ps ON ps.student_id=s.id
            WHERE ps.parent_user_id=%s
            ORDER BY s.full_name
        """, (user_id,))

    elif role == "admin":
        students = query("""
            SELECT id, student_number, full_name
            FROM public.school_students
            ORDER BY full_name
        """)

    else:
        abort(403)

    selected = request.args.get("student", type=int)
    allowed_ids = {s["id"] for s in students}

    if selected not in allowed_ids:
        selected = students[0]["id"] if students else None

    marks = []
    if selected is not None:
        marks = query("""
            SELECT subject, exam_name, term, score
            FROM public.exam_results
            WHERE student_id=%s
            ORDER BY term, exam_name, subject
        """, (selected,))

    return page("Results", """
    <h1>Student results</h1>
    {% if students %}
      <div class="card">
      <form method="get">
       <label>Select student</label>
       <select name="student" onchange="this.form.submit()">
        {% for s in students %}
        <option value="{{ s.id }}"
          {{ 'selected' if s.id == selected else '' }}>
          {{ s.full_name }} ({{ s.student_number }})
        </option>
        {% endfor %}
       </select>
       <noscript><p><button>View results</button></p></noscript>
      </form>
      </div>

      <div class="card">
       <h2>Results</h2>
       <div class="wrap"><table>
        <tr><th>Subject</th><th>Exam</th><th>Term</th><th>Score</th></tr>
        {% for m in marks %}
        <tr><td>{{ m.subject }}</td><td>{{ m.exam_name }}</td>
        <td>{{ m.term }}</td><td>{{ m.score }}%</td></tr>
        {% else %}
        <tr><td colspan="4">No results available.</td></tr>
        {% endfor %}
       </table></div>
      </div>
    {% else %}
      <div class="card">
       <p>No student record is linked to this account yet.
       Contact the school administrator.</p>
      </div>
    {% endif %}
    """, students=students, marks=marks, selected=selected)


