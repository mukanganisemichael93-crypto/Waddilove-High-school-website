@app.route("/login", methods=["GET", "POST"])
def login():
    if session.get("user_id"):
        return redirect(url_for("admin" if session.get("role") == "admin"
                                else "results"))

    if request.method == "POST":
        username = request.form.get("username", "").strip()
        password = request.form.get("password", "")

        users = query("""
            SELECT id, username, full_name, password_hash, role, active
            FROM public.school_users
            WHERE username=%s
            LIMIT 1
        """, (username,))

        if (users and users[0]["active"]
                and check_password_hash(users[0]["password_hash"], password)):
            user = users[0]
            session.clear()
            session["user_id"] = user["id"]
            session["username"] = user["username"]
            session["full_name"] = user["full_name"]
            session["role"] = user["role"]
            session["_csrf"] = secrets.token_urlsafe(32)

            flash("Welcome, " + user["full_name"] + ".")
            if user["role"] == "admin":
                return redirect(url_for("admin"))
            return redirect(url_for("results"))

        flash("Incorrect username or password.", "error")

    return page("Sign in", """
    <h1>Sign in</h1>
    <div class="card">
    <form method="post">
      <input type="hidden" name="_csrf" value="{{ csrf_token() }}">
      <label>Username</label>
      <input name="username" required maxlength="120" autocomplete="username">
      <label>Password</label>
      <input type="password" name="password" required
             autocomplete="current-password">
      <p><button type="submit">Sign in</button></p>
    </form>
    </div>
    """)


