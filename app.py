def csrf_token():
    if "_csrf" not in session:
        session["_csrf"] = secrets.token_urlsafe(32)
    return session["_csrf"]


@app.context_processor
def template_globals():
    return {
        "csrf_token": csrf_token,
        "year": datetime.now().year,
    }


@app.before_request
def protect_forms():
    if request.method == "POST":
        sent = request.form.get("_csrf", "")
        expected = session.get("_csrf", "")

        if not expected or not hmac.compare_digest(sent, expected):
            abort(400, "Security token expired. Refresh the page.")


def login_required(fn):
    @wraps(fn)
    def wrapper(*args, **kwargs):
        if not session.get("user_id"):
            flash("Please sign in first.", "error")
            return redirect(url_for("login"))
        return fn(*args, **kwargs)
    return wrapper


def admin_required(fn):
    @wraps(fn)
    def wrapper(*args, **kwargs):
        if session.get("role") != "admin":
            abort(403)
        return fn(*args, **kwargs)
    return wrapper


def page(title, body, **context):
    # Render the page content first so its Jinja variables are evaluated.
    body_html = render_template_string(body, **context)
    return render_template_string(BASE, title=title, body=body_html)


