def init_db():
    statements = [
        """
        CREATE TABLE IF NOT EXISTS public.school_users (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username TEXT UNIQUE NOT NULL,
            full_name TEXT NOT NULL,
            password_hash TEXT NOT NULL,
            role TEXT NOT NULL
                CHECK (role IN ('admin', 'student', 'parent')),
            active BOOLEAN NOT NULL DEFAULT TRUE,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS public.school_classes (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT UNIQUE NOT NULL,
            level TEXT NOT NULL DEFAULT '',
            teacher TEXT NOT NULL DEFAULT '',
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS public.school_students (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            student_number TEXT UNIQUE NOT NULL,
            full_name TEXT NOT NULL,
            class_id BIGINT REFERENCES public.school_classes(id)
                ON DELETE SET NULL,
            user_id BIGINT UNIQUE REFERENCES public.school_users(id)
                ON DELETE SET NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS public.parent_students (
            parent_user_id BIGINT NOT NULL
                REFERENCES public.school_users(id) ON DELETE CASCADE,
            student_id BIGINT NOT NULL
                REFERENCES public.school_students(id) ON DELETE CASCADE,
            PRIMARY KEY (parent_user_id, student_id)
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS public.exam_results (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            student_id BIGINT NOT NULL
                REFERENCES public.school_students(id) ON DELETE CASCADE,
            subject TEXT NOT NULL,
            exam_name TEXT NOT NULL,
            score NUMERIC(5,2) NOT NULL CHECK (score >= 0 AND score <= 100),
            term TEXT NOT NULL DEFAULT '',
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
            UNIQUE (student_id, subject, exam_name, term)
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS public.school_posts (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            title TEXT NOT NULL,
            body TEXT NOT NULL,
            published BOOLEAN NOT NULL DEFAULT FALSE,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS public.school_enquiries (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            full_name TEXT NOT NULL,
            email TEXT NOT NULL DEFAULT '',
            phone TEXT NOT NULL DEFAULT '',
            message TEXT NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS public.school_settings (
            key TEXT PRIMARY KEY,
            value TEXT NOT NULL DEFAULT ''
        )
        """,
    ]

    with dbconn() as conn:
        for statement in statements:
            conn.execute(statement)

        # Supports databases created by an earlier version of this app.
        conn.execute("""
            ALTER TABLE public.school_students
            ADD COLUMN IF NOT EXISTS user_id BIGINT
            REFERENCES public.school_users(id) ON DELETE SET NULL
        """)

        conn.execute("""
            CREATE UNIQUE INDEX IF NOT EXISTS school_students_user_id_unique
            ON public.school_students(user_id)
            WHERE user_id IS NOT NULL
        """)


def init_admin():
    username = os.getenv("ADMIN_USERNAME", "").strip()
    password = os.getenv("ADMIN_PASSWORD", "")

    if not username or len(password) < 12:
        raise RuntimeError(
            "Set ADMIN_USERNAME and ADMIN_PASSWORD (at least 12 characters) in .env"
        )

    users = query(
        "SELECT id, role FROM public.school_users WHERE username=%s",
        (username,)
    )

    if users:
        if users[0]["role"] != "admin":
            raise RuntimeError(
                "ADMIN_USERNAME already belongs to a non-admin account. "
                "Choose a different username."
            )
        return

    execute(
        """
        INSERT INTO public.school_users
            (username, full_name, password_hash, role)
        VALUES (%s, %s, %s, 'admin')
        """,
        (username, "School Administrator",
         generate_password_hash(password))
    )


